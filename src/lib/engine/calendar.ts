import { tzOffsetMinutes } from "./time";

/**
 * The scheduled announcements that move every market at once: Fed and ECB
 * rate decisions, US inflation (CPI) and jobs (NFP) figures. Dates from the
 * official calendars (federalreserve.gov, ecb.europa.eu, bls.gov), read on
 * 2 November 2026; the later ones are the dates scheduled then.
 */

export type EventKind = "fed" | "cpi" | "nfp" | "ecb";

export const EVENT_KINDS: { kind: EventKind; label: string; short: string; zone: string }[] = [
  { kind: "fed", label: "Décision de la Fed", short: "Fed", zone: "America/New_York" },
  { kind: "cpi", label: "Inflation US (CPI)", short: "CPI", zone: "America/New_York" },
  { kind: "nfp", label: "Emploi US (NFP)", short: "NFP", zone: "America/New_York" },
  { kind: "ecb", label: "Décision de la BCE", short: "BCE", zone: "Europe/Berlin" },
];

/** The calendar holds every announcement from this day… */
export const CALENDAR_FROM = Date.UTC(2017, 0, 1);
/** …to this one, excluded. */
export const CALENDAR_TO = Date.UTC(2028, 0, 1);

export interface MarketEvent {
  kind: EventKind;
  /** Day of the announcement where it is made (New York, or Frankfurt for the ECB): "2024-06-12". */
  day: string;
  /** That local day in UTC: start included, end excluded. */
  start: number;
  end: number;
}

let events: MarketEvent[] | null = null;

/** Every announcement, sorted by day. */
export function marketEvents(): MarketEvent[] {
  if (events) return events;
  events = EVENT_KINDS.flatMap(({ kind, zone }) =>
    DATES[kind]
      .trim()
      .split(/\s+/)
      .map((day) => {
        const [y, m, d] = day.split("-").map(Number);
        const midnight = Date.UTC(y, m - 1, d);
        // The offset at midday: no clock change falls on an announcement day.
        const start = midnight - tzOffsetMinutes(zone, midnight + 12 * 3_600_000) * 60_000;
        return { kind, day, start, end: start + 86_400_000 };
      }),
  ).sort((a, b) => a.start - b.start);
  return events;
}

/** The announcements whose day overlaps [from, to]: those a trade open over that span lived through. */
export function eventsBetween(from: number, to: number): MarketEvent[] {
  const all = marketEvents();
  // Every day lasts as long, so the ends are sorted like the starts.
  let lo = 0;
  let hi = all.length;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (all[mid].end <= from) lo = mid + 1;
    else hi = mid;
  }
  const out: MarketEvent[] = [];
  for (let i = lo; i < all.length && all[i].start <= to; i++) out.push(all[i]);
  return out;
}

